function relativeDate(day) {
  if (!Number.isInteger(day) || day === 0) throw new Error(`Day offsets must be non-zero whole numbers, got ${day}`);
  return `P${day}D`;
}

function absoluteDate(today) {
  const [y, m, d] = today.split('-').map(Number);
  return (day) => new Date(Date.UTC(y, m - 1, d + day, 9)).toISOString().replace('Z', '+0000');
}

const statusChange = (created, from, to) => ({
  created,
  items: [{ fieldType: 'jira', field: 'status', fromString: from, toString: to }],
});

function toIssue(item, fmt, roleLabel) {
  const issue = { externalId: item.ext, summary: item.summary };
  if (item.description) issue.description = item.description;
  issue.issueType = item.type;
  issue.status = item.status;
  if (item.status === 'Done') issue.resolution = 'Done';
  issue.priority = item.priority;
  issue.created = fmt(item.created);
  issue.updated = fmt(item.done ?? item.ip ?? item.created);
  if (item.due !== undefined) issue.duedate = fmt(item.due);
  issue.components = item.components;
  if (item.fixVersion) issue.fixedVersions = [item.fixVersion];
  if (roleLabel) issue.labels = [roleLabel];
  const history = [];
  if (item.ip !== undefined) history.push(statusChange(fmt(item.ip), 'To Do', 'In Progress'));
  if (item.done !== undefined) history.push(statusChange(fmt(item.done), 'In Progress', 'Done'));
  if (history.length) issue.history = history;
  return issue;
}

// Labels never go on epics: the evidence engine matches comparable epics on components
// and labels, and a shared seed label would make every epic comparable.
const roleLabelFor = (item, opts, roleNames) =>
  opts.roleLabels && item.type !== 'Epic' && item.role !== UNASSIGNED ? `seed-role-${roleNames[item.role]}` : undefined;

function buildImportFile(model, fmt, opts, roleNames) {
  const issuesOf = (space) => model.items
    .filter((i) => i.space === space)
    .sort((a, b) => a.created - b.created) // stable: keys follow creation order
    .map((i) => toIssue(i, fmt, roleLabelFor(i, opts, roleNames)));
  const description = opts.today
    ? `Seeded demo history generated by Forewarned's seed script. All dates are as of ${opts.today}.`
    : RELATIVE_DESCRIPTION;
  return {
    projects: [
      {
        name: 'Checkout', key: 'CHK', description,
        versions: CHK_VERSIONS.map(([name, released, day]) => ({ name, released, releaseDate: fmt(day) })),
        components: CHK_COMPONENTS,
        issues: issuesOf('CHK'),
      },
      {
        name: 'Platform', key: 'PLT', description,
        versions: [],
        components: PLT_COMPONENTS,
        issues: issuesOf('PLT'),
      },
    ],
    links: [
      ...model.items.filter((i) => i.parent).map((i) => ({
        name: 'Epic-Story Link', sourceId: model.byRef.get(i.parent).ext, destinationId: i.ext,
      })),
      ...model.blocks.map((b) => ({ name: 'Blocks', sourceId: b.from.ext, destinationId: b.to.ext })),
    ],
  };
}

function personNames(personas) {
  const names = new Set();
  for (const r of personas.roles) {
    names.add(r.persona);
    if (!r.displayName.startsWith('TODO')) {
      names.add(r.displayName);
      names.add(r.displayName.split(' ')[0]);
    }
  }
  return [...names];
}

const escapeRegExp = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// AC 7: refuse to write a file that names a user.
function assertNoUsers(value, names, path = '$') {
  if (Array.isArray(value)) {
    value.forEach((v, i) => assertNoUsers(v, names, `${path}[${i}]`));
  } else if (value && typeof value === 'object') {
    for (const [key, v] of Object.entries(value)) {
      if (USER_KEYS.includes(key)) {
        throw new Error(`Refusing to write ${DEMO_FILE}: user key "${key}" at ${path}. The importer would create an inactive user.`);
      }
      assertNoUsers(v, names, `${path}.${key}`);
    }
  } else if (typeof value === 'string') {
    const hit = names.find((n) => new RegExp(`\\b${escapeRegExp(n)}\\b`, 'i').test(value));
    if (hit) throw new Error(`Refusing to write ${DEMO_FILE}: person name "${hit}" at ${path}. The file must name no users.`);
  }
}

