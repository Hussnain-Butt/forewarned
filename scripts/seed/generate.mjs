function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const pad = (n) => String(n).padStart(2, '0');
const extId = (role, space, tag) => `${role}-${space.toLowerCase()}-${tag}`;

function buildModel() {
  const rand = mulberry32(RANDOM_SEED);
  const between = (lo, hi) => {
    if (lo > hi) throw new Error(`Empty date window ${lo}..${hi}; check the seed content.`);
    return lo + Math.floor(rand() * (hi - lo + 1));
  };
  const priorityFor = (type) => {
    const r = rand();
    if (type === 'Bug') return r < 0.5 ? 'High' : 'Medium';
    if (type === 'Task') return r < 0.3 ? 'Low' : 'Medium';
    return r < 0.25 ? 'High' : 'Medium';
  };

  const items = [];
  const byRef = new Map();
  const blockerOf = new Map(BLOCKS.map(([from, to]) => [to, from]));
  const add = (item) => {
    if (byRef.has(item.ref)) throw new Error(`Duplicate seed reference ${item.ref}`);
    items.push(item);
    byRef.set(item.ref, item);
    return item;
  };

  function addEpic(space, spec) {
    const finished = spec.done !== undefined;
    const epic = add({
      ref: `${space}/${spec.tag}`, ext: extId(spec.role, space, spec.tag), space, type: 'Epic',
      role: spec.role, summary: spec.summary, description: spec.description, priority: spec.priority,
      status: finished ? 'Done' : spec.status, created: spec.created, ip: spec.start,
      done: spec.done, due: spec.due ?? undefined, components: spec.components, parent: null,
    });
    spec.children.forEach(([type, role, summary, openStatus, fixed = {}], index) => {
      const tag = `${spec.tag}-${pad(index + 1)}`;
      const ref = `${space}/${tag}`;
      const status = finished ? 'Done' : openStatus;
      // A blocked child starts only after its blocker is resolved.
      const blocker = byRef.get(blockerOf.get(ref));
      const earliestIp = Math.max(spec.start + 1, blocker?.done !== undefined ? blocker.done + 1 : -Infinity);
      const created = fixed.created ?? (index < spec.atStart
        ? between(spec.created + 1, spec.start - 2)
        : between(spec.start + 2, finished ? spec.done - 12 : -3));
      let ip;
      let done;
      if (status !== 'To Do') {
        const lastIp = finished ? spec.done - 3 : status === 'Done' ? -2 : -1;
        ip = fixed.ip ?? between(Math.max(created + 1, earliestIp), lastIp);
      }
      if (status === 'Done') {
        done = fixed.done ?? between(ip + 1, Math.min(ip + 21, finished ? spec.done - 1 : -1));
      }
      add({
        ref, ext: extId(role, space, tag), space, type, role, summary, priority: priorityFor(type),
        status, created, ip, done, due: fixed.due, components: spec.components, parent: epic.ref,
      });
    });
  }

  // PLT first, so CHK children can start after their blockers are resolved.
  PLT_EPICS.forEach((spec) => addEpic('PLT', spec));
  for (const t of PLT_TASKS) {
    add({
      ref: `PLT/${t.tag}`, ext: extId(t.role, 'PLT', t.tag), space: 'PLT', type: t.type, role: t.role,
      summary: t.summary, priority: priorityFor(t.type), status: 'Done', created: t.created, ip: t.ip,
      done: t.done, due: t.due, components: ['Shared services'], parent: null,
    });
  }
  CHK_EPICS.forEach((spec) => addEpic('CHK', spec));

  for (const item of items) item.fixVersion = fixVersionFor(item);
  const blocks = BLOCKS.map(([from, to]) => {
    if (!byRef.has(from) || !byRef.has(to)) throw new Error(`Unknown work item in Blocks link ${from} -> ${to}`);
    return { from: byRef.get(from), to: byRef.get(to) };
  });
  return { items, byRef, blocks };
}

// Finished CHK work items ship in the first release on or after their done day; the
// Checkout v2 epic and its children are planned for the unreleased Checkout 2.0.
function fixVersionFor(item) {
  if (item.space !== 'CHK') return undefined;
  if (item.ref === CURRENT_EPIC || item.parent === CURRENT_EPIC) return NEXT_VERSION;
  if (item.status !== 'Done') return undefined;
  const release = CHK_VERSIONS.find(([, released, day]) => released && day >= item.done);
  return release ? release[0] : NEXT_VERSION;
}

